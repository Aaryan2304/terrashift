"""Consolidated data audit.

Reproduces every number recorded in PLAN.md section 1.4 and writes
outputs/audit/data_audit.md plus the supporting JSON files.

Run after: data/safeloader.py, data/masks.py, scripts/utilities/run_registration.py,
scripts/utilities/run_normalization.py.
"""

import csv
import json
import os

import numpy as np


from terrashift.data.manifest import load_manifest
from terrashift.data.safeloader import SafeProduct, BAND_ORDER, canonical_band
from terrashift.data.masks import QualityMasks, CLASSI_BANDS
from terrashift.preprocessing.indices import normalized_difference

OUT_DIR = "outputs/audit"

MANIFEST = load_manifest()
# (product id, pair, absolute path)
PRODUCTS = [(p["id"], p["pair"], p["path"]) for p in MANIFEST["products"]]

# 10 m windows used for the radiometry example
SEA_WINDOW = ((1000, 2000), (1000, 2000))      # Arabian Sea, 10 m grid
LAND_WINDOW = ((7000, 8000), (6000, 7000))     # Mumbai-Thane land, 10 m grid


def reflectance_table(product, band, window_10m):
    """Mean reflectance in a 10 m window, using the band's own grid.

    The raw DN is recovered from the product's own quantification value and
    radiometric offset, not from hardcoded constants.
    """
    res = product.resolution[canonical_band(band)]
    r0, r1 = window_10m[0]
    c0, c1 = window_10m[1]
    r0 = r0 * 10 // res
    r1 = r1 * 10 // res
    c0 = c0 * 10 // res
    c1 = c1 * 10 // res
    a, _, _ = product.read_band(band, window=((r0, r1), (c0, c1)))
    refl = float(np.nanmean(a))
    dn = refl * product.quantification - product.offset_for(band)
    return refl, dn


def main():
    os.makedirs(OUT_DIR, exist_ok=True)
    lines = []

    def w(s=""):
        print(s)
        lines.append(s)

    w("# Data audit")
    w("")
    w("Generated by `scripts/audit/audit.py`. Every number comes from the four supplied")
    w("Sentinel-2A MSI Level-1C products.")
    w("")

    # ---------------------------------------------------------------- 1. products
    w("## 1. Product inventory")
    w("")
    w("| ID | Pair | Tile | Quantification | Offset (all bands) |")
    w("|----|------|------|----------------|--------------------|")
    prods = {}
    for pid, pair, path in PRODUCTS:
        p = SafeProduct(path)
        prods[pid] = p
        offsets = sorted(set(p.offsets.values()))
        w("| %s | %s | %s | %d | %s |" % (
            pid, pair, p.name.split("_T")[-1].split("_")[0],
            int(p.quantification), ", ".join(str(int(o)) for o in offsets)))
    w("")

    # ---------------------------------------------------------------- 2. bands
    w("## 2. Bands and native resolution")
    w("")
    w("| Band | Resolution | Central wavelength (nm) |")
    w("|------|-----------|-------------------------|")
    p0 = prods["QBB_2022_12_23"]
    for b in BAND_ORDER:
        canon = canonical_band(b)
        wl = p0.wavelength.get(canon)
        wl_txt = "%.1f" % wl if wl is not None else "?"
        w("| %s | %d m | %s |" % (b, p0.resolution[canon], wl_txt))
    w("")

    # ---------------------------------------------------------------- 3. radiometry
    w("## 3. Radiometric conversion")
    w("")
    w("Formula (ESA, PB 04.00 and later):")
    w("")
    w("    reflectance = (DN + RADIO_ADD_OFFSET) / QUANTIFICATION_VALUE")
    w("    DN = 0 is NO_DATA")
    w("")
    w("Read from the product metadata:")
    w("")
    w("- QUANTIFICATION_VALUE = %d" % int(p0.quantification))
    w("- RADIO_ADD_OFFSET = %s for all 13 bands in all four products" %
      ", ".join(str(int(o)) for o in sorted(set(p0.offsets.values()))))
    w("")
    w("### 3.1 Arabian Sea window, Pair A")
    w("")
    w("Each band uses its own native grid. The 20 m band uses half the row and")
    w("column indices of the 10 m window.")
    w("")
    w("| Band | Resolution | Raw DN | Corrected reflectance |")
    w("|------|-----------|--------|-----------------------|")
    sea = {}
    for b in ["B03", "B04", "B08", "B11"]:
        refl, dn = reflectance_table(prods["QBB_2022_12_23"], b, SEA_WINDOW)
        sea[b] = {"raw_dn": dn, "reflectance": refl}
        w("| %s | %d m | %.1f | %.4f |" % (
            b, p0.resolution[canonical_band(b)], dn, refl))
    w("")

    # ---------------------------------------------------------------- 4. water
    w("## 4. Water fraction and thresholds")
    w("")
    w("NDWI (McFeeters) = (B03 - B08) / (B03 + B08), computed at 100 m.")
    w("")
    w("| Product | NDWI > -0.2 | NDWI > -0.1 | NDWI > 0.0 | NDWI > 0.1 | NDWI > 0.2 |")
    w("|---------|-------------|-------------|------------|------------|------------|")
    for pid, pair, safe in PRODUCTS:
        p = prods[pid]
        b03, _, _ = p.read_band("B03", out_shape=(1098, 1098))
        b08, _, _ = p.read_band("B08", out_shape=(1098, 1098))
        ndwi = normalized_difference(b03, b08)
        valid = np.isfinite(ndwi)
        fracs = []
        for t in [-0.2, -0.1, 0.0, 0.1, 0.2]:
            fracs.append(float(((ndwi > t) & valid).sum()) / valid.sum() * 100)
        w("| %s | %.2f%% | %.2f%% | %.2f%% | %.2f%% | %.2f%% |" % (
            pid, *fracs))
    w("")
    w("Bands are resampled to the 100 m grid with bilinear interpolation. The")
    w("resampling method changes the fraction by about one percentage point;")
    w("nearest-neighbour resampling gives 63.10% and 61.01% for Pair A.")
    w("The threshold 0.0 is the physical boundary of the McFeeters index and is")
    w("the most stable across dates. The threshold 0.2 is not stable.")
    w("")

    # ---------------------------------------------------------------- 5. masks
    w("## 5. Quality masks")
    w("")
    w("MSK_CLASSI band order: 1 opaque cloud, 2 cirrus, 3 snow and ice.")
    w("")
    w("| Product | Opaque cloud | Cirrus | Snow/ice |")
    w("|---------|--------------|--------|----------|")
    for pid, pair, safe in PRODUCTS:
        qm = QualityMasks(prods[pid])
        classi, _, _ = qm.read_classi()
        counts = {CLASSI_BANDS[i]: int(classi[i].sum()) for i in range(3)}
        w("| %s | %d | %d | %d |" % (pid, counts["opaque_cloud"],
                                    counts["cirrus"], counts["snow_ice"]))
    w("")
    w("MSK_QUALIT is all zero in all four products. MSK_DETFOO holds detector")
    w("footprint indices (6 to 12), not a cloud mask.")
    w("")

    # ---------------------------------------------------------------- 6. registration
    w("## 6. Registration")
    w("")
    reg_path = os.path.join(OUT_DIR, "registration.json")
    if os.path.isfile(reg_path):
        reg = json.load(open(reg_path))
        w("| Pair | Initial dx | Initial dy | Initial correlation | Residual dx | Residual dy | Residual RMSE |")
        w("|------|-----------|-----------|---------------------|------------|------------|---------------|")
        for k, v in reg.items():
            i = v["initial"]
            r = i.get("residual", {})
            w("| %s | %.2f m | %.2f m | %.3f | %.2f m | %.2f m | %.4f |" % (
                k, i["median_dx_m"], i["median_dy_m"], i["median_correlation"],
                r.get("median_dx_m", float("nan")), r.get("median_dy_m", float("nan")),
                r.get("rmse_mean", float("nan"))))
        w("")
        w("ECC on B08 at 10 m over five land windows per pair. Pair A has one")
        w("window that did not converge. The residual is measured after applying")
        w("the median global translation.")
    else:
        w("registration.json not found. Run scripts/utilities/run_registration.py first.")
    w("")

    # ---------------------------------------------------------------- 7. normalisation
    w("## 7. Normalisation comparison")
    w("")
    norm_path = os.path.join(OUT_DIR, "normalization_comparison.csv")
    if os.path.isfile(norm_path):
        with open(norm_path) as fh:
            rows = list(csv.DictReader(fh))
        w("| Pair | Method | MAE before | MAE after | Reduction | Change score before | Change score after |")
        w("|------|--------|-----------|-----------|-----------|---------------------|--------------------|")
        for r in rows:
            w("| %s | %s | %.5f | %.5f | %.1f%% | %.4f | %.4f |" % (
                r["pair"], r["method"], float(r["mae_before"]),
                float(r["mae_after"]), float(r["mae_reduction_pct"]),
                float(r["change_score_before"]), float(r["change_score_after"])))
        w("")
        w("The validation set is a spatial half of the stable land pixels. The")
        w("fit set is the other half. The change score is the standard deviation")
        w("of the per-pixel change magnitude on the validation pixels.")
    else:
        w("normalization_comparison.csv not found. Run scripts/utilities/run_normalization.py first.")
    w("")

    # ---------------------------------------------------------------- write
    md = "\n".join(lines) + "\n"
    with open(os.path.join(OUT_DIR, "data_audit.md"), "w") as fh:
        fh.write(md)
    print("\nwrote", os.path.join(OUT_DIR, "data_audit.md"))


if __name__ == "__main__":
    main()
